  var sprache = 'de';

  function setLang(l) { sprache = TEXTE[l] ? l : 'de'; return sprache; }
  function lang() { return sprache; }
  function locale() { return sprache === 'en' ? 'en-GB' : 'de-AT'; }

  function einsetzen(text, werte) {
    if (!werte) { return text; }
    return text.replace(/\{(\w+)\}/g, function (m, k) {
      return Object.prototype.hasOwnProperty.call(werte, k) ? String(werte[k]) : m;
    });
  }

  function t(schluessel, werte) {
    var tab = TEXTE[sprache];
    var text = Object.prototype.hasOwnProperty.call(tab, schluessel) ? tab[schluessel]
      : (Object.prototype.hasOwnProperty.call(TEXTE.de, schluessel) ? TEXTE.de[schluessel] : schluessel);
    return einsetzen(text, werte);
  }

  function tn(schluessel, n, werte) {
    var w = werte ? Object.assign({}, werte) : {};
    w.n = n;
    return t(schluessel + (n === 1 ? '.1' : '.n'), w);
  }

  function datum(iso, lang) {
    var d = new Date(iso);
    if (isNaN(d.getTime())) { return ''; }
    return d.toLocaleDateString(lang === 'en' || (!lang && sprache === 'en') ? 'en-GB' : 'de-AT', { day: '2-digit', month: '2-digit', year: 'numeric' });
  }

  /* „vor 3 Monaten“ aus einer Anzahl Tage. */
  function vorTagen(tage) {
    if (tage === null || tage === undefined || isNaN(tage)) { return ''; }
    if (tage < 1) { return t('zeit.heute'); }
    if (tage < 2) { return t('zeit.gestern'); }
    if (tage < 30) { return t('zeit.tage', { n: tage }); }
    var monate = Math.floor(tage / 30.44);
    if (monate < 12) { return monate <= 1 ? t('zeit.monat') : t('zeit.monate', { n: monate }); }
    var jahre = Math.floor(tage / 365.25);
    return jahre <= 1 ? t('zeit.jahr') : t('zeit.jahre', { n: jahre });
  }

  function schluessel(l) { return Object.keys(TEXTE[l] || {}); }

